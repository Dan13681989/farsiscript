// کتابخانهٔ تست نویسی (ساده)

تعداد_تست_ها = 0;
تعداد_موفقیت = 0;

تابع تست_کن(نام, شرط) {
    تعداد_تست_ها = تعداد_تست_ها + 1;
    اگر (شرط) {
        تعداد_موفقیت = تعداد_موفقیت + 1;
        چاپ "✅ " + نام;
    } درغیراینصورت {
        چاپ "❌ " + نام;
    }
}

تابع نتیجه_تست() {
    چاپ "تست‌ها: " + تبدیل_به_رشته(تعداد_موفقیت) + " / " + تبدیل_به_رشته(تعداد_تست_ها);
}
